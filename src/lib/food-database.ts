export type FoodCategory =
  | 'Indian Foods'
  | 'Grains & Breads'
  | 'Dals & Curries'
  | 'Dairy & Eggs'
  | 'Poultry, Meat & Fish'
  | 'Fruits & Vegetables'
  | 'Nuts, Seeds & Spreads'
  | 'Snacks, Sweets & Street Food'
  | 'International & Packaged'
  | 'Beverages'
  | 'Supplements';

export interface ServingOption {
  unit: string;
  label: string;
  grams: number;
}

export interface FoodItem {
  id: string;
  name: string;
  brand: string;
  category: FoodCategory;
  subcategory?: string;
  is_supplement?: boolean;
  barcode?: string;
  default_unit: string;
  default_quantity: number;
  servings: ServingOption[];
  // Nutritional values standardized per 100g (or per 100ml for liquids)
  per100g: {
    calories: number;
    protein_g: number;
    carbs_g: number;
    fat_g: number;
    saturated_fat_g: number;
    unsaturated_fat_g: number;
    fiber_g: number;
    sugar_g: number;
    sodium_mg: number;
    cholesterol_mg: number;
  };
  ingredients?: string;
  micronutrients_note?: string;
}

export interface CalculatedFoodNutrition {
  total_grams: number;
  calories: number;
  protein_g: number;
  carbs_g: number;
  fat_g: number;
  saturated_fat_g: number;
  unsaturated_fat_g: number;
  fiber_g: number;
  sugar_g: number;
  sodium_mg: number;
  cholesterol_mg: number;
}

const r1 = (n: number) => Math.round(n * 10) / 10;

/**
 * Multiply a food item's verified per-100g nutrition by the selected serving unit & quantity.
 */
export function calculateFoodNutrition(
  food: FoodItem,
  quantity: number,
  unit: string
): CalculatedFoodNutrition {
  const safeQty = Math.max(0, Number(quantity) || 0);
  const matchedServing = food.servings.find((s) => s.unit === unit);
  let gramsPerUnit = matchedServing ? matchedServing.grams : 1;

  if (!matchedServing) {
    switch (unit) {
      case 'g':
      case 'ml':
        gramsPerUnit = 1;
        break;
      case 'kg':
      case 'L':
        gramsPerUnit = 1000;
        break;
      case 'tbsp':
        gramsPerUnit = 15;
        break;
      case 'tsp':
        gramsPerUnit = 5;
        break;
      case 'cup':
      case 'glass':
        gramsPerUnit = 240;
        break;
      case 'katori':
        gramsPerUnit = 150;
        break;
      case 'bowl':
        gramsPerUnit = 250;
        break;
      default:
        gramsPerUnit = food.servings[0]?.grams || 100;
    }
  }

  const totalGrams = safeQty * gramsPerUnit;
  const factor = totalGrams / 100;
  const p = food.per100g;

  return {
    total_grams: r1(totalGrams),
    calories: Math.round(p.calories * factor),
    protein_g: r1(p.protein_g * factor),
    carbs_g: r1(p.carbs_g * factor),
    fat_g: r1(p.fat_g * factor),
    saturated_fat_g: r1((p.saturated_fat_g || 0) * factor),
    unsaturated_fat_g: r1((p.unsaturated_fat_g || 0) * factor),
    fiber_g: r1((p.fiber_g || 0) * factor),
    sugar_g: r1((p.sugar_g || 0) * factor),
    sodium_mg: Math.round((p.sodium_mg || 0) * factor),
    cholesterol_mg: Math.round((p.cholesterol_mg || 0) * factor),
  };
}

